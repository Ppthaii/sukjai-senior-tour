/**
 * ฟังก์ชันหาภูมิภาคอัตโนมัติตามชื่อจังหวัด
 * @param {string} provinceName - ชื่อจังหวัด เช่น "นครปฐม" หรือ "จ.นครปฐม"
 * @returns {string} ภูมิภาค เช่น "ภาคกลาง", "ภาคเหนือ", "ภาคตะวันออก"
 */
export function getRegionByProvince(provinceName) {
  if (!provinceName || typeof provinceName !== 'string') return 'ภาคกลาง';
  
  // ตัดคำนำหน้า เช่น "จ.", "จังหวัด", "เมือง" และช่องว่าง
  const cleanName = provinceName
    .replace(/^(จังหวัด|จ\.|เมือง)\s*/g, '')
    .trim();

  // ตรวจสอบในแม็พ
  if (PROVINCE_TO_REGION[cleanName]) {
    return PROVINCE_TO_REGION[cleanName];
  }

  // ค้นหาแบบบางส่วนเผื่อพิมพ์ติดคำอื่น
  for (const [prov, reg] of Object.entries(PROVINCE_TO_REGION)) {
    if (cleanName.includes(prov) || prov.includes(cleanName)) {
      return reg;
    }
  }

  return 'ภาคกลาง'; // ค่าเริ่มต้น
}
